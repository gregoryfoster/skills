def _env() -> dict:
    """No inherited GIT_*: under a hook GIT_DIR would point the fixture at this repo (#189)."""
    return {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}


def _repo(tmp_path: Path, files: dict[str, str]) -> Path:
    root = tmp_path / "repo"
    for rel, body in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    subprocess.run(["git", "-C", str(root), "init", "-q"], check=True, env=_env())
    subprocess.run(["git", "-C", str(root), "add", "-A"], check=True, env=_env())
    return root


def _inventory(root: Path, *args: str) -> dict:
    proc = subprocess.run(
        ["bash", str(INVENTORY), "--repo-root", str(root), *args],
        capture_output=True,
        text=True,
        env=_env(),
        timeout=60,
    )
    assert proc.returncode == 0, proc.stderr
    return json.loads(proc.stdout)


