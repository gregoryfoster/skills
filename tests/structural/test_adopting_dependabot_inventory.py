def _job(inv: dict, workflow: str, job: str) -> dict:
    wf = next(w for w in inv["workflows"] if w["file"].endswith(workflow))
    return next(j for j in wf["jobs"] if j["id"] == job)


def test_no_config_reads_as_none(watcher):
    assert watcher["dependabot_config"] is None


def test_each_job_is_classed_by_what_ci_needs(watcher):
    """Phase 1: a job that needs nothing passes on a Dependabot PR regardless."""
    assert _job(watcher, "ci.yml", "css")["needs"] == "nothing"
    test = _job(watcher, "ci.yml", "test")
    assert test["needs"] == "oidc"
    assert test["vars"] == ["GCP_WIF_PROVIDER"]
    assert test["private_index_steps"] == ["Sync the wheelhouse"]
    release = _job(watcher, "ci.yml", "release")
    assert release["needs"] == "secret"
    assert release["secrets"] == ["RELEASE_TOKEN"]
    assert release["write_permissions"] == ["contents"], (
        "a Dependabot run's token is read-only"
    )


def test_a_job_inherits_the_workflow_permissions(tmp_path):
    """A job that declares none takes the workflow's, OIDC included; its own replace them."""
    wf = (
        "on: pull_request\npermissions:\n  id-token: write\njobs:\n"
        "  a:\n    runs-on: x\n    steps: [{run: 'true'}]\n"
        "  b:\n    runs-on: x\n    permissions:\n      contents: read\n    steps: [{run: 'true'}]\n"
    )
    inv = _inventory(_repo(tmp_path, {".github/workflows/ci.yml": wf}))
    assert _job(inv, "ci.yml", "a")["needs"] == "oidc"
    assert _job(inv, "ci.yml", "b")["needs"] == "nothing"


def test_triggers_and_scheduled_only(watcher):
    by_file = {Path(w["file"]).name: w for w in watcher["workflows"]}
