def test_pin_forms(watcher):
    forms = {
        (Path(r["file"]).name, r["ref"]): r["form"] for r in watcher["actions"]["refs"]
    }
    assert forms[("ci.yml", "actions/checkout@v5")] == "major"
    assert (
        forms[("ci.yml", "actions/checkout@08eba0b27e820071cde6df949e0beb9ba4906955")]
        == "sha"
    )
    assert forms[("ci.yml", "astral-sh/setup-uv@v5")] == "major", (
        "a quoted ref is still read"
    )
    assert forms[("ci.yml", "./.github/actions/setup")] == "local"
    assert forms[("action.yml", "actions/cache@v4")] == "major", (
        "a composite action's uses: counts"
    )
    sha = next(r for r in watcher["actions"]["refs"] if r["form"] == "sha")
    assert sha["comment"] == "v4.3.0"


