"""adopting-dependabot's inventory.sh: what Dependabot would see, read from a fixture repo (#376).

Each test builds a throwaway git repo shaped like one of the two cohort
adoptions the skill comes from: watcher (WIF and OIDC in CI, a private
wheelhouse, a generated workflow) and notifier (two uv tables, no secrets).
The upstream tag reading is tested on canned ``git ls-remote`` output, so
nothing here reaches the network.
"""

