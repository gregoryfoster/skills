"""Alembic migration environment — async PostgreSQL.

Generated by init-project-fastapi. Reads DATABASE_URL through src.core.config
(the environment, or systemd's credentials directory), falling back to
alembic.ini's sqlalchemy.url for offline tooling. An online run refuses a
production-looking database without the ALLOW_PRODUCTION_DB opt-in, as the app
does: a migration is as dangerous as a request.

To extend with a custom type renderer (e.g. ULIDType → sa.String(26)),
define `render_item` and pass it to context.configure() in both
do_run_migrations and run_migrations_offline.
"""

import asyncio
from logging.config import fileConfig

from sqlalchemy.ext.asyncio import create_async_engine

from alembic import context
from src.core.config import get_database_url
from src.core.db_safety import assert_database_safety
from src.core.models import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def get_url() -> str:
    """The configured DATABASE_URL, else alembic.ini's (offline tooling)."""
    try:
        return get_database_url()
    except RuntimeError:
        return config.get_main_option("sqlalchemy.url", "")


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode — emit SQL without connecting."""
    context.configure(
        url=get_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection) -> None:
    """Run migrations using a sync connection."""
    context.configure(connection=connection, target_metadata=target_metadata)
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    """Run migrations in 'online' mode — async connection."""
    connectable = create_async_engine(get_url())
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode — connect to the database."""
    assert_database_safety()
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
